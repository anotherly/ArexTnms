USE arex_tnms;

-- Operator decisions are web-owned. Source event keys are immutable strings GW-A-id/GW-H-id.
CREATE TABLE IF NOT EXISTS web_fault_process_info (
  FAULT_KEY VARCHAR(100) NOT NULL,
  DSBLTY_JGMT_CD VARCHAR(20) DEFAULT NULL,
  PRCS_STTS_CD VARCHAR(20) NOT NULL DEFAULT 'UNCONFIRMED',
  DSBLTY_TYPE_NM VARCHAR(100) DEFAULT NULL,
  DSBLTY_OCRN_CN TEXT DEFAULT NULL,
  DSBLTY_OCRN_PLC_NM VARCHAR(200) DEFAULT NULL,
  IDNTY_USER_ID VARCHAR(20) DEFAULT NULL,
  MGMT_MEMO_CN TEXT DEFAULT NULL,
  TEMP_ACTION_YN CHAR(1) NOT NULL DEFAULT 'N',
  COMPLETE_YN CHAR(1) NOT NULL DEFAULT 'N',
  REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MDFCN_DT DATETIME DEFAULT NULL,
  PRIMARY KEY (FAULT_KEY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='웹 자체 장애 판단 및 조치 상태';
CREATE TABLE IF NOT EXISTS web_fault_process_action (
  ACTION_SN BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  FAULT_KEY VARCHAR(100) NOT NULL,
  ACTN_SE_CD VARCHAR(20) NOT NULL,
  ACTN_CN TEXT,
  SYMPTOM TEXT,
  REASON TEXT,
  RESULT_CN TEXT,
  PLAN TEXT,
  ACTOR_ID VARCHAR(20),
  ACTOR_NAME VARCHAR(100),
  ACTN_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(ACTION_SN), INDEX IX_WEB_FAULT_ACTION_KEY(FAULT_KEY,ACTN_DT),
  CONSTRAINT FK_WEB_FAULT_ACTION FOREIGN KEY(FAULT_KEY) REFERENCES web_fault_process_info(FAULT_KEY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='웹 장애 조치 이력';

CREATE TABLE IF NOT EXISTS web_dsblty_excp_group_info (
  EXCP_GROUP_SN BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  EXCP_GROUP_NM VARCHAR(100) NOT NULL,
  EXCP_GROUP_EXPLN VARCHAR(1000),
  USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
  REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  RGTR_ID VARCHAR(20), MDFCN_DT DATETIME, MDFR_ID VARCHAR(20),
  PRIMARY KEY(EXCP_GROUP_SN)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='웹 장애 예외그룹';
CREATE TABLE IF NOT EXISTS web_dsblty_excp_group_eqpmnt_rel (
  EXCP_GROUP_SN BIGINT UNSIGNED NOT NULL,
  EMS_ID INT NOT NULL,
  DEVICE_ID VARCHAR(50) NOT NULL,
  ALL_IDCT_YN CHAR(1) NOT NULL DEFAULT 'Y',
  REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(EXCP_GROUP_SN,EMS_ID,DEVICE_ID),
  INDEX IX_WEB_EXCP_MEMBER_DEVICE(EMS_ID,DEVICE_ID),
  CONSTRAINT FK_WEB_EXCP_MEMBER_GROUP FOREIGN KEY(EXCP_GROUP_SN) REFERENCES web_dsblty_excp_group_info(EXCP_GROUP_SN) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='웹 예외그룹 대상 com 장비 복합키';
CREATE TABLE IF NOT EXISTS web_dsblty_excp_schdl_info (
  EXCP_SCHDL_SN BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  EXCP_GROUP_SN BIGINT UNSIGNED NOT NULL,
  EXCP_SCHDL_NM VARCHAR(100) NOT NULL,
  BGNG_DT DATETIME NOT NULL,
  END_DT DATETIME DEFAULT NULL,
  NO_END_YN CHAR(1) NOT NULL DEFAULT 'N',
  REPT_START_TM TIME DEFAULT NULL,
  REPT_END_TM TIME DEFAULT NULL,
  REPT_CYCLE_CN VARCHAR(100) NOT NULL DEFAULT 'ONCE',
  EXCP_RSN VARCHAR(2000),
  USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
  REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, RGTR_ID VARCHAR(20), MDFCN_DT DATETIME, MDFR_ID VARCHAR(20),
  PRIMARY KEY(EXCP_SCHDL_SN),INDEX IX_WEB_EXCP_SCHDL_RANGE(EXCP_GROUP_SN,BGNG_DT,END_DT),
  CONSTRAINT FK_WEB_EXCP_SCHEDULE_GROUP FOREIGN KEY(EXCP_GROUP_SN) REFERENCES web_dsblty_excp_group_info(EXCP_GROUP_SN) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='웹 장애 예외일정';
CREATE TABLE IF NOT EXISTS web_dsblty_excp_schdl_grd_rel (
  EXCP_SCHDL_SN BIGINT UNSIGNED NOT NULL,
  DSBLTY_GRD_CD VARCHAR(20) NOT NULL,
  REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(EXCP_SCHDL_SN,DSBLTY_GRD_CD),
  CONSTRAINT FK_WEB_EXCP_SCHDL_GRD FOREIGN KEY(EXCP_SCHDL_SN) REFERENCES web_dsblty_excp_schdl_info(EXCP_SCHDL_SN) ON DELETE CASCADE
