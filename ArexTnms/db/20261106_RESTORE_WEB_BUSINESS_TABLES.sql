CREATE TABLE IF NOT EXISTS web_thrshld_info (
  THRSHLD_SN BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  THRSHLD_PROFILE_NM VARCHAR(100) NOT NULL,
  LINK_SYS_CD VARCHAR(20) DEFAULT NULL,
  PERF_IDCT_CD VARCHAR(20) NOT NULL,
  INFO_VL DECIMAL(8,2), WARNING_VL DECIMAL(8,2), LOW_VL DECIMAL(8,2), HIGH_VL DECIMAL(8,2), EMERGENCY_VL DECIMAL(8,2),
  CONTN_NOCS INT NOT NULL DEFAULT 3,
  USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
