USE arex_tnms;
CREATE TABLE IF NOT EXISTS web_cd_color_info (
 COM_CD_GROUP_ID CHAR(7) NOT NULL COMMENT '공통코드 그룹',
 COM_CD CHAR(11) NOT NULL COMMENT '공통코드',
 COLOR_HEX CHAR(7) NOT NULL COMMENT '#RRGGBB',
 PRIMARY KEY (COM_CD_GROUP_ID,COM_CD),
 CONSTRAINT FK_WEB_CODE_COLOR FOREIGN KEY (COM_CD_GROUP_ID,COM_CD)
   REFERENCES com_cd_info(COM_CD_GROUP_ID,COM_CD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='웹 공통코드 색상';
