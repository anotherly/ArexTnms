USE arex_tnms;
-- 테이블 신규 컬럼 확인
SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT
  FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'com_ping_info'
 ORDER BY ORDINAL_POSITION;
-- 시스템/설정 개수와 활성 여부 확인
SELECT EMS_ID, DATA_SE_CD, USE_YN, EXCN_TM, CYCLE_CRTR_CN,
       PERF_CLCT_USE_YN, PING_MNTR_USE_YN, CLCT_CYCLE_SEC,
       STTS_MNTR_CYCLE_SEC, TIMEOUT_SEC, RTRY_NOCS, TIMEOUT_POLL_SEC
  FROM com_ping_info ORDER BY EMS_ID, DATA_SE_CD;
-- 권한 확인
SELECT A.AUTHRT_CD, A.REG_AUTHRT_YN, A.DTL_AUTHRT_YN, A.MDFCN_AUTHRT_YN, A.DEL_AUTHRT_YN
  FROM web_authrt_menu_rel A
  JOIN web_menu_info M ON M.MENU_SN = A.MENU_SN
 WHERE M.MENU_URL_ADDR LIKE '/performance/cycle.do%';
